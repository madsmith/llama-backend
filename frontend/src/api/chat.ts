// Chat page data model, browser persistence, streaming parse and title summarisation.

/** llama-server's per-request timings (absent from vLLM and other servers). */
export interface Timings {
  cache_n?: number;
  prompt_n?: number;
  prompt_per_second?: number;
  predicted_n?: number;
  predicted_per_second?: number;
}

export interface Usage {
  prompt_tokens?: number;
  completion_tokens?: number;
}

/** Client-side measurements, plus whatever the server reported. */
export interface Stats {
  tSend: number;
  tFirst?: number;
  tLast?: number;
  /** Streamed chunks carrying text; ~1 token each on llama-server, may batch on vLLM. */
  chunks: number;
  timings?: Timings;
  usage?: Usage;
}

export interface Msg {
  role: "user" | "assistant";
  content: string;
  /** Model the message was sent to (user) or generated by (assistant). */
  model?: string;
  reasoning?: string;
  error?: string;
  stats?: Stats;
}

export interface ChatSession {
  id: number;
  /** Short model-generated blurb; null until one has been produced. */
  title: string | null;
  /** Number of messages the current title was generated from. */
  titledAt: number;
  model: string;
  messages: Msg[];
  createdAt: number;
  updatedAt: number;
}

// ----- persistence -----

const CHATS_KEY = "chat:sessions";
const ACTIVE_KEY = "chat:active";

export function loadChats(): ChatSession[] {
  try {
    const raw = localStorage.getItem(CHATS_KEY);
    const parsed = raw ? JSON.parse(raw) : [];
    return Array.isArray(parsed) ? parsed : [];
  } catch {
    return [];
  }
}

export function saveChats(chats: ChatSession[]): void {
  try {
    localStorage.setItem(CHATS_KEY, JSON.stringify(chats));
  } catch {
    // quota exceeded or storage unavailable; keep running in memory
  }
}

export function loadActiveId(): number | null {
  try {
    const v = localStorage.getItem(ACTIVE_KEY);
    return v ? Number(v) : null;
  } catch {
    return null;
  }
}

export function saveActiveId(id: number | null): void {
  try {
    if (id === null) localStorage.removeItem(ACTIVE_KEY);
    else localStorage.setItem(ACTIVE_KEY, String(id));
  } catch { /* ignore */ }
}

export function newChat(chats: ChatSession[], model: string): ChatSession {
  const id = chats.reduce((max, c) => Math.max(max, c.id), 0) + 1;
  const now = Date.now();
  return { id, title: null, titledAt: 0, model, messages: [], createdAt: now, updatedAt: now };
}

export const chatLabel = (c: ChatSession) => c.title ?? `New Chat ${c.id}`;

/** Messages in OpenAI format: errored turns are dropped, UI-only fields stripped. */
export function toApiMessages(messages: Msg[], systemPrompt: string) {
  return [
    ...(systemPrompt.trim() ? [{ role: "system", content: systemPrompt.trim() }] : []),
    ...messages.filter((m) => !m.error).map((m) => ({ role: m.role, content: m.content })),
  ];
}

// ----- streaming -----

export interface Chunk {
  content?: string;
  reasoning?: string;
  error?: string;
  timings?: Timings;
  usage?: Usage;
}

/** Parse one SSE `data:` payload from /v1/chat/completions. */
export function parseChunk(payload: string): Chunk | null {
  if (payload === "[DONE]") return null;
  try {
    const j = JSON.parse(payload);
    if (j.error) return { error: errorText(j.error) };
    const delta = j.choices?.[0]?.delta ?? {};
    return {
      content: delta.content || undefined,
      // llama-server uses reasoning_content; vLLM uses reasoning.
      reasoning: delta.reasoning_content || delta.reasoning || undefined,
      timings: j.timings ?? undefined,
      usage: j.usage ?? undefined,
    };
  } catch {
    return null;
  }
}

export function errorText(err: unknown): string {
  if (typeof err === "string") return err;
  if (err && typeof err === "object" && "message" in err) return String((err as { message: unknown }).message);
  return JSON.stringify(err);
}

// ----- stats -----

const fmtRate = (r: number) => (r >= 100 ? r.toFixed(0) : r.toFixed(1));

/**
 * Build the stats line. Server timings are used when present; otherwise rates
 * are estimated from client-side stream timing and marked with "~".
 */
export function formatStats(s: Stats, pending: boolean): string | null {
  if (s.tFirst === undefined) return null;
  const parts: string[] = [`TTFT ${((s.tFirst - s.tSend) / 1000).toFixed(2)}s`];
  const t = s.timings;

  if (t?.predicted_per_second !== undefined && !pending) {
    parts.push(`${fmtRate(t.predicted_per_second)} tok/s`);
  } else {
    const n = s.usage?.completion_tokens ?? s.chunks;
    const dt = ((s.tLast ?? s.tFirst) - s.tFirst) / 1000;
    if (n > 1 && dt > 0) parts.push(`~${fmtRate((n - 1) / dt)} tok/s`);
  }
  const genTokens = t?.predicted_n ?? s.usage?.completion_tokens;
  parts.push(genTokens !== undefined ? `${genTokens} tokens` : `~${s.chunks} tokens`);

  const promptTokens = s.usage?.prompt_tokens ?? (t?.prompt_n !== undefined ? t.prompt_n + (t.cache_n ?? 0) : undefined);
  if (promptTokens !== undefined) {
    let p = `prompt ${promptTokens}`;
    if (t?.cache_n) p += ` (${t.cache_n} cached)`;
    if (t?.prompt_per_second !== undefined) p += ` @ ${fmtRate(t.prompt_per_second)} tok/s`;
    parts.push(p);
  }
  return parts.join(" · ");
}

// ----- title summarisation -----

const TITLE_MAX_MSGS = 10;
const TITLE_MAX_CHARS_PER_MSG = 1000;

function cleanTitle(raw: string): string | null {
  let t = raw.replace(/<think>[\s\S]*?<\/think>/gi, "").trim();
  t = t.split("\n").map((l) => l.trim()).find(Boolean) ?? "";
  t = t.replace(/^(title|chat title)\s*:\s*/i, "");
  t = t.replace(/^["'`*#\s]+|["'`*.\s]+$/g, "");
  if (!t) return null;
  const words = t.split(/\s+/);
  if (words.length > 8) t = words.slice(0, 8).join(" ");
  return t.length > 60 ? t.slice(0, 57).trimEnd() + "…" : t;
}

async function requestTitle(model: string, prompt: string, maxTokens: number, signal?: AbortSignal) {
  const res = await fetch("/api/chat/completions", {
    method: "POST",
    headers: { "content-type": "application/json" },
    signal,
    body: JSON.stringify({
      model,
      stream: false,
      max_tokens: maxTokens,
      temperature: 0.3,
      // Keep reasoning models brief. Templates differ: Qwen-style honours
      // enable_thinking, gpt-oss-style honours reasoning_effort; others ignore both.
      reasoning_effort: "low",
      chat_template_kwargs: { enable_thinking: false, reasoning_effort: "low" },
      messages: [{ role: "user", content: prompt }],
    }),
  });
  if (!res.ok) return null;
  const j = await res.json();
  const content = j.choices?.[0]?.message?.content;
  return typeof content === "string" ? content : null;
}

/**
 * Ask the chat's own model for a few-word title. Returns null on any failure so
 * the caller keeps the "New Chat N" fallback.
 */
export async function summarizeChat(chat: ChatSession, signal?: AbortSignal): Promise<string | null> {
  const turns = chat.messages.filter((m) => !m.error && m.content).slice(-TITLE_MAX_MSGS);
  if (!turns.some((m) => m.role === "assistant")) return null;

  const transcript = turns
    .map((m) => `${m.role === "user" ? "User" : "Assistant"}: ${m.content.slice(0, TITLE_MAX_CHARS_PER_MSG)}`)
    .join("\n\n");
  const prompt = `Conversation:\n\n${transcript}\n\nWrite a 2-5 word title for this conversation. Reply with only the title.`;

  try {
    // Generous budget: models that reason anyway need room to finish before answering.
    const content = await requestTitle(chat.model, prompt, 2048, signal);
    return content ? cleanTitle(content) : null;
  } catch {
    return null;
  }
}
